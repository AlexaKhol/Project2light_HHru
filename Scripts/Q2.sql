--Запрос 2 для поиска регионов, в которых сосредоточено наибольшее кол-во объявлений 
SELECT area,COUNT(id) AS num_vac
FROM public.parcing_table
GROUP BY area
ORDER BY num_vac DESC;

--SHORT REPORT
-- Москва и Санкт-Петербург - лидеры по количеству вакансий, однако Москва значимо превосходит рынок вакансий Санкт-Петербурга.
-- Данный факт связан с тем, что это крупнейшие города страны с развитой инфраструктурой бизнеса.
-- В Екатеринбурге, Нижнем Новгороде и Новосибирске также значительное количество вакансий. 
-- Это указывает на развитый рынок труда для аналитиков в этих регионах.