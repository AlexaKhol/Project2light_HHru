--Запрос 8 для выявления основных работодателей (указать запраты и условия труда) для аналитиков данных и 
--системных аналитиков
SELECT employer,COUNT(id) AS num_vac, ROUND(AVG(salary_from),2) AS avg_salary_from, 
ROUND(AVG(salary_to),2) AS avg_salary_to, schedule, employment
FROM public.parcing_table
WHERE name LIKE '%Аналитик данных%' OR name LIKE '%аналитик данных%' OR name LIKE '%Системный аналитик%' OR name LIKE '%системный аналитик%'
GROUP BY employer, schedule, employment
ORDER BY num_vac DESC;

--SHORT REPORT
-- СБЕР выделяется как основной работодатель для аналитиков данных и системных аналитиков (аналогично Запросу 3, СБЕР -
-- является крупнейшим работодателем) с 117 вакансиями и средней зарплатой от 110583.33 рублей до 73333.33 рублей. 
-- Средняя зарплата "до" ниже средней зарплаты "от" - скорее всего из-за того, что
-- СБЕР часто пишет сумму "до", не указываю сумму "от" при размещении вакансий. 
-- Основной тип занятости в СБЕР — полная занятость с полным рабочим днём. 
-- Значит, компания предпочитает длительное сотрудничество с сотрудниками.
-- Банк ВТБ (ПАО) и Ozon также предлагают достаточно вакансий с аналогичными условиями занятости.
-- Это подтверждает тенденцию крупных компаний нанимать аналитиков данных и системных аналитиков 
-- на полную занятость с фиксированным рабочим графиком.