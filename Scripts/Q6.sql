--Запрос 6 для определения распределения грейдов по опыту среди аналитиков данных и системных аналитиков 
SELECT experience,COUNT(id) AS num_vac
FROM public.parcing_table
GROUP BY experience 
ORDER BY num_vac DESC;

--SHORT REPORT
-- Наибольшее количество вакансий (1091) предназначено для специалистов с опытом от 1 до 3 лет (Junior+), 
-- что свидетельствует о высоком спросе на специалистов начального и среднего уровней. 
-- Вакансий для Middle-специалистов (3–6 лет) так же много, в то время как спрос 
-- на Senior-специалистов (6+ лет) крайне низкий.
-- Это может быть связано с ограниченным кол-вом таких специалистов на рынке, а также удержанием работадателя
-- такого специалиста в компании.
-- Нужно учитывать, что Senior-аналитиков могут чаще искать по другим каналам, а не на HH.ru.