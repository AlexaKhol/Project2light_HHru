SELECT experience,
       COUNT(*) AS num_vac,
       ROUND(COUNT(*) * 100.0 / 1326, 2) AS percent_vac
FROM public.parcing_table
WHERE name LIKE '%Аналитик данных%' 
   OR name LIKE '%аналитик данных%'
   OR name LIKE '%Системный аналитик%'
   OR name LIKE '%системный аналитик%'
GROUP BY experience
ORDER BY percent_vac DESC;

