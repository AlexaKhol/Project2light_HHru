--Запрос 9 для определения наиболее востребованных навыков для различных грейдов и позиций 
SELECT key_skills_1, experience, COUNT(*) AS quant_numb
FROM public.parcing_table
WHERE key_skills_1 IS NOT NULL
GROUP BY key_skills_1, experience
ORDER BY quant_numb DESC;

--SHORT REPORT
-- Среди ключевых навыков чаще упоминается «Анализ данных» (196 упоминаний), 
-- что логично для позиций аналитиков данных. SQL (100 упоминаний) и MS SQL (49 упоминаний) также являются
-- важными навыками, что подчёркивает важность работы с базами данных. «Документация» (49 упоминаний) 
-- указывает на необходимость ведения точных записей и отчётов. Это актуально для системных аналитиков.
-- Интересно, что в топ ключевых навыков не входит Python, однако его часто подразумевают под навыком "Анализ данных".